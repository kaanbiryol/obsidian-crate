const source = resolve('node_modules/@tabler/icons/icons/outline');
const entries = [];
for (const [id, name] of Object.entries(ICONS)) {
	const svg = await readFile(resolve(source, `${name}.svg`), 'utf8');
	// Keep the drawing only; the renderers supply the 24px viewBox and stroke attributes.
	const body = svg.slice(svg.indexOf('>', svg.indexOf('<svg')) + 1, svg.lastIndexOf('</svg>'))
		.replace(/<path stroke="none" d="M0 0h24v24H0z" fill="none"\s*\/>/, '')
		.replace(/\s*\n\s*/g, '').trim();
	entries.push(`\t${JSON.stringify(id)}: ${JSON.stringify(body)},`);
}

const output = `// Generated by scripts/generate-tabler-icons.mjs from @tabler/icons (MIT). Do not edit.
export const TABLER_ICONS: Record<string, string> = {
${entries.join('\n')}
};
`;
await writeFile(resolve('src/ui/shared/icons/tabler-icons.generated.ts'), output);
console.log(`Wrote ${entries.length} Tabler icons.`);
